# 1. Creating an empty list
list1 = []
print("Empty List:", list1)

# 2. Creating a list with elements
list2 = [10, 20, 30, 40, 50]
print("List with elements:", list2)

# 3. Creating a list with different data types
list3 = [10, "Python", 20.5, True]
print("List with different data types:", list3)

# 4. Creating a list using list() constructor
list4 = list((1, 2, 3, 4, 5))
print("List using list() constructor:", list4)

# 5. Creating a list from a string
list5 = list("PYTHON")
print("List from string:", list5)

# 6. Creating a list using range()
list6 = list(range(1, 6))
print("List using range():", list6)

# 7. Creating a nested list
list7 = [[1, 2], [3, 4], [5, 6]]
print("Nested List:", list7)