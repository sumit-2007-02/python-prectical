# 1. Creating an empty tuple
tuple1 = ()
print("1. Empty Tuple:", tuple1)

# 2. Creating a tuple with elements
tuple2 = (10, 20, 30, 40, 50)
print("2. Tuple with elements:", tuple2)

# 3. Creating a tuple without parentheses
tuple3 = 10, 20, 30
print("3. Tuple without parentheses:", tuple3)

# 4. Creating a tuple with different data types
tuple4 = (10, "Python", 20.5, True)
print("4. Tuple with different data types:", tuple4)

# 5. Creating a tuple using tuple() constructor
tuple5 = tuple([1, 2, 3, 4, 5])
print("5. Using tuple() constructor:", tuple5)

# 6. Creating a tuple from a string
tuple6 = tuple("PYTHON")
print("6. Tuple from string:", tuple6)

# 7. Creating a tuple using range()
tuple7 = tuple(range(1, 6))
print("7. Tuple using range():", tuple7)

# 8. Creating a single-element tuple
tuple8 = (10,)
print("8. Single-element tuple:", tuple8)

# 9. Creating a nested tuple
tuple9 = ((1, 2), (3, 4), (5, 6))
print("9. Nested Tuple:", tuple9)