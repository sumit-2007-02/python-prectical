# 1. Creating an empty set
set1 = set()
print("1. Empty Set:", set1)

# 2. Creating a set with elements
set2 = {10, 20, 30, 40, 50}
print("2. Set with elements:", set2)

# 3. Creating a set using set() constructor
set3 = set([1, 2, 3, 4, 5])
print("3. Using set() constructor:", set3)

# 4. Creating a set from a string
set4 = set("PYTHON")
print("4. Set from string:", set4)

# 5. Creating a set using range()
set5 = set(range(1, 6))
print("5. Set using range():", set5)

# 6. Creating a set with different data types
set6 = {10, "Python", 20.5, True}
print("6. Set with different data types:", set6)

# 7. Creating a set with duplicate values
set7 = {10, 20, 10, 30, 20}
print("7. Set with duplicate values:", set7)