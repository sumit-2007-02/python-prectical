# Example 1: Addition
add = lambda a, b: a + b
print("Addition =", add(10, 20))

# Example 2: Square of a number
square = lambda n: n * n
print("Square =", square(5))

# Example 3: Cube of a number
cube = lambda n: n * n * n
print("Cube =", cube(3))

# Example 4: Find maximum of two numbers
maximum = lambda a, b: a if a > b else b
print("Maximum =", maximum(15, 10))