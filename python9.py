print("Example of break statement:")
for i in range(1, 11):
    if i == 6:
        break  
    print(i)


print("\nExample of continue statement:")
for i in range(1, 11):
    if i == 6:
        continue   
    print(i)


print("\nExample of pass statement:")
for i in range(1, 6):
    if i == 3:
        pass   
    print(i)
